#include <iostream>
#include <stack>
#include <string>
using namespace std;

int main() {
    // Ввод строки со скобками
    cout << "Входные данные: s = ";
    string s;
    getline(cin, s); // Считываем всю строку (даже если есть пробелы)

    // Создаем стек для хранения открывающих скобок
    stack<char> st;

    // Проходим по всем символам строки
    for (int i = 0; i < s.length(); i++) {
        char c = s[i]; // Текущий символ

        // Если символ - открывающая скобка
        if (c == '(' || c == '[' || c == '{') {
            st.push(c); // Кладем в стек
        }
        // Если символ - закрывающая скобка
        else if (c == ')' || c == ']' || c == '}') {
            // Проверяем: есть ли в стеке открывающая скобка?
            if (st.empty()) {
                cout << "Выходные данные: false" << endl; // Нет открывающей скобки - ошибка
                return 0; // Завершаем программу
            }

            // Берем последнюю открывающую скобку из стека
            char top = st.top();

            //  Проверяем: совпадают ли типы скобок?
            if ((c == ')' && top == '(') ||
                (c == ']' && top == '[') ||
                (c == '}' && top == '{')) {
                st.pop(); // Скобки совпали - удаляем открывающую из стека
            }
            else {
                cout << "Выходные данные: false" << endl; // Типы не совпали - ошибка
                return 0; // Завершаем программу
            }
        }
    }

    //  Проверяем: все ли открывающие скобки были закрыты?
    if (st.empty()) {
        cout << "Выходные данные: true" << endl; // Стек пуст - все скобки правильно закрыты
    }
    else {
        cout << "Выходные данные: false" << endl; // В стеке остались незакрытые скобки
    }

    return 0;
}