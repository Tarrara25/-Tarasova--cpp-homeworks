#include <iostream>  
#include <algorithm>     // для функции sort (сортировки)
using namespace std;

int main() {
    int n;               // размер массива
    int arr[100];        // массив
    int x;               // число, которое будем искать
    cout << "Введите размер массива: ";
    cin >> n;

    // Ввод элементов массива
    cout << "Введите элементы массива: ";
    for (int i = 0; i < n; i++) {
        cin >> arr[i];   // считываем каждый элемент
    }

    // Ввод числа для поиска
    cout << "Введите число для поиска: ";
    cin >> x;

    // Сортируем массив по возрастанию
    sort(arr, arr + n);

    // Бинарный поиск
    int left = 0;        // начало массива
    int right = n - 1;   // конец массива
    int index = -1;      // индекс найденного элемента (-1 если не найден)

    // Пока есть что искать
    while (left <= right) {
        // Находим середину текущего диапазона
        int mid = (left + right) / 2;

        // Если нашли нужное число
        if (arr[mid] == x) {
            index = mid;     // запоминаем индекс
            break;           
        }
        // Если число в середине меньше искомого
        else if (arr[mid] < x) {
            left = mid + 1;  // ищем в правой половине
        }
        // Если число в середине больше искомого
        else {
            right = mid - 1; // ищем в левой половине
        }
    }

    cout << "Индекс искомого элемента: " << index << endl;

    return 0;
}